NAV_LINK = '    <a href="#r15"><span class="n">10</span>Pre-release (r15)</a>'


def splice():
    s = open(BOARD).read()
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: SECTION, s, flags=re.S)
    else:
        s = s.replace("\n</main>", "\n" + SECTION + "\n\n</main>", 1)
    if 'href="#r15"' not in s:
        s = s.replace('    <a href="#states"><span class="n">09</span>System states</a>', '    <a href="#states"><span class="n">09</span>System states</a>\n' + NAV_LINK, 1)
    s = s.replace("<span>v3 mobile · flutter app · round 10</span>", "<span>v3 mobile · flutter app · round 15</span>")
    open(BOARD, "w").write(s)


if __name__ == "__main__":
    if "--splice" in sys.argv:
        splice()
    else:
        print(SECTION)
